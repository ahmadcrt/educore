const $=s=>document.querySelector(s);
const show=(el,t,ok)=>{el.textContent=t;el.className="msg "+(ok?"ok":"err")};
const NOKEYS="Add your Supabase URL and anon key in js/config.js first.";
const login=$("#login-form"),reg=$("#register-form"),reset=$("#reset-btn");
if(login)login.addEventListener("submit",async e=>{e.preventDefault();const m=$("#msg");
  if(!window.configured)return show(m,NOKEYS);
  const f=new FormData(login);const{error}=await sb.auth.signInWithPassword({email:f.get("email"),password:f.get("password")});
  error?show(m,error.message):location.href="courses.html"});
if(reg)reg.addEventListener("submit",async e=>{e.preventDefault();const m=$("#msg"),f=new FormData(reg);
  if(!window.configured)return show(m,NOKEYS);
  if(f.get("password").length<8)return show(m,"Use a password with at least 8 characters.");
  const{error}=await sb.auth.signUp({email:f.get("email"),password:f.get("password"),options:{data:{full_name:f.get("name")}}});
  error?show(m,error.message):show(m,"Account created. Check your email to confirm, then log in.",true)});
if(reset)reset.addEventListener("click",async()=>{const m=$("#msg"),email=$("#email").value;
  if(!window.configured)return show(m,NOKEYS);
  if(!email)return show(m,"Enter your email above first.");
  const{error}=await sb.auth.resetPasswordForEmail(email);
  error?show(m,error.message):show(m,"Reset link sent. Check your inbox.",true)});
(async()=>{const a=$("#auth-link");if(!a||!window.configured)return;
  const{data}=await sb.auth.getSession();
  if(data.session){a.textContent="Log out";a.href="#";a.onclick=async e=>{e.preventDefault();await sb.auth.signOut();location.href="index.html"}}})();
